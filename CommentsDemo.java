/**
 * 文档注释（JavaDoc）
 * @author WANG
 * @version 1.0
 * 这个类是用于演示注释的用法
 */
public class CommentsDemo {
    public static void main(String[] args) {
        // 单行注释：打印一句话
        System.out.println("注意看注释的区别");

        /*
         * 这是多行注释
         * 这里面的字，程序运行时会完全忽略。
         * 我经常用它来"注释掉"一大段代码，防止它们运行。
         */
    }
}